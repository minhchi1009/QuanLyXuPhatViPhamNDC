/*
    ConstraintsAndIndexes.sql
    Khóa ngoại, ràng buộc toàn vẹn, unique và index phục vụ tìm kiếm.
*/
USE [QuanLyXuPhatNongDoCon];
GO
SET ANSI_NULLS ON;
SET QUOTED_IDENTIFIER ON;
GO

/* ================= KHÓA NGOẠI ================= */
ALTER TABLE dbo.CAN_BO
    ADD CONSTRAINT FK_CAN_BO_VAI_TRO FOREIGN KEY (VaiTro) REFERENCES dbo.VAI_TRO (Ma_VaiTro);

ALTER TABLE dbo.TAI_KHOAN
    ADD CONSTRAINT FK_TAI_KHOAN_CAN_BO FOREIGN KEY (Ma_CanBo) REFERENCES dbo.CAN_BO (Ma_CanBo);

ALTER TABLE dbo.LOAI_VI_PHAM
    ADD CONSTRAINT FK_LVP_LOAI_PHUONG_TIEN FOREIGN KEY (Ma_LoaiPhuongTien) REFERENCES dbo.LOAI_PHUONG_TIEN (Ma_LoaiPhuongTien),
        CONSTRAINT FK_LVP_MUC_NONG_DO FOREIGN KEY (Ma_MucNongDoCon) REFERENCES dbo.MUC_NONG_DO_CON (Ma_MucNongDoCon);

ALTER TABLE dbo.VI_PHAM
    ADD CONSTRAINT FK_VV_LOAI_VI_PHAM FOREIGN KEY (Ma_LoaiViPham) REFERENCES dbo.LOAI_VI_PHAM (Ma_LoaiViPham),
        CONSTRAINT FK_VV_LOAI_PHUONG_TIEN FOREIGN KEY (Ma_LoaiPhuongTien) REFERENCES dbo.LOAI_PHUONG_TIEN (Ma_LoaiPhuongTien),
        CONSTRAINT FK_VV_MUC_NONG_DO FOREIGN KEY (Ma_MucNongDoCon) REFERENCES dbo.MUC_NONG_DO_CON (Ma_MucNongDoCon),
        CONSTRAINT FK_VV_CAN_BO FOREIGN KEY (Ma_CanBo) REFERENCES dbo.CAN_BO (Ma_CanBo),
        CONSTRAINT FK_VV_NGUOI_VI_PHAM FOREIGN KEY (Ma_NguoiViPham) REFERENCES dbo.NGUOI_VI_PHAM (Ma_NguoiViPham),
        CONSTRAINT FK_VV_TRANG_THAI FOREIGN KEY (Ma_TrangThaiThanhToan) REFERENCES dbo.TRANG_THAI_THANH_TOAN (Ma_TrangThaiThanhToan);

ALTER TABLE dbo.QUYET_DINH_XU_PHAT
    ADD CONSTRAINT FK_QD_VI_PHAM FOREIGN KEY (Ma_VuViec) REFERENCES dbo.VI_PHAM (Ma_VuViec),
        CONSTRAINT FK_QD_TRANG_THAI FOREIGN KEY (Ma_TrangThaiThanhToan) REFERENCES dbo.TRANG_THAI_THANH_TOAN (Ma_TrangThaiThanhToan);

ALTER TABLE dbo.THANH_TOAN
    ADD CONSTRAINT FK_TT_QUYET_DINH FOREIGN KEY (Ma_QuyetDinh) REFERENCES dbo.QUYET_DINH_XU_PHAT (Ma_QuyetDinh),
        CONSTRAINT FK_TT_CAN_BO FOREIGN KEY (Ma_CanBo) REFERENCES dbo.CAN_BO (Ma_CanBo);
GO

/* ================= RÀNG BUỘC MIỀN GIÁ TRỊ ================= */
ALTER TABLE dbo.NGUOI_VI_PHAM
    ADD CONSTRAINT CK_NVP_CCCD CHECK (LEN(CanCuocCongDan) = 12 AND CanCuocCongDan NOT LIKE '%[^0-9]%'),
        CONSTRAINT CK_NVP_SDT CHECK (SoDienThoai LIKE '0%' AND SoDienThoai NOT LIKE '%[^0-9]%' AND LEN(SoDienThoai) BETWEEN 10 AND 11),
        CONSTRAINT CK_NVP_GIOITINH CHECK (GioiTinh IN (N'Nam', N'Nữ'));

ALTER TABLE dbo.CAN_BO
    ADD CONSTRAINT CK_CB_CCCD CHECK (LEN(CanCuocCongDan) = 12 AND CanCuocCongDan NOT LIKE '%[^0-9]%'),
        CONSTRAINT CK_CB_SDT CHECK (SoDienThoai LIKE '0%' AND SoDienThoai NOT LIKE '%[^0-9]%' AND LEN(SoDienThoai) BETWEEN 10 AND 11);

ALTER TABLE dbo.TAI_KHOAN
    ADD CONSTRAINT CK_TK_TENDANGNHAP CHECK (LEN(TenDangNhap) BETWEEN 3 AND 50 AND TenDangNhap NOT LIKE '%[^A-Za-z0-9._-]%'),
        CONSTRAINT CK_TK_EMAIL CHECK (Email LIKE '%_@_%._%'),
        CONSTRAINT CK_TK_MATKHAU CHECK (LEN(MatKhau) >= 20);

ALTER TABLE dbo.MUC_NONG_DO_CON
    ADD CONSTRAINT CK_MND_NGUONG CHECK (NguongTren IS NULL OR NguongTren > 0);

ALTER TABLE dbo.LOAI_VI_PHAM
    ADD CONSTRAINT CK_LVP_MUCPHAT CHECK (MucPhat >= 0);

ALTER TABLE dbo.VI_PHAM
    ADD CONSTRAINT CK_VV_NONGDO CHECK (NongDoCon >= 0),
        CONSTRAINT CK_VV_BIENSO CHECK (LEN(RTRIM(BienSoXe)) >= 4);

ALTER TABLE dbo.QUYET_DINH_XU_PHAT
    ADD CONSTRAINT CK_QD_SOTIEN CHECK (SoTienPhat >= 0),
        CONSTRAINT CK_QD_NGAYNOP CHECK (NgayNopPhat IS NULL OR NgayNopPhat >= NgayRaQuyetDinh);

ALTER TABLE dbo.THANH_TOAN
    ADD CONSTRAINT CK_TT_SOTIEN CHECK (SoTien > 0),
        CONSTRAINT CK_TT_PHUONGTHUC CHECK (PhuongThuc IN (N'Tiền mặt', N'Chuyển khoản'));
GO

/* ================= UNIQUE ================= */
ALTER TABLE dbo.VAI_TRO
    ADD CONSTRAINT UQ_VAI_TRO_TEN UNIQUE (TenVaiTro);

ALTER TABLE dbo.NGUOI_VI_PHAM
    ADD CONSTRAINT UQ_NVP_CCCD UNIQUE (CanCuocCongDan),
        CONSTRAINT UQ_NVP_SDT UNIQUE (SoDienThoai);

ALTER TABLE dbo.CAN_BO
    ADD CONSTRAINT UQ_CB_CCCD UNIQUE (CanCuocCongDan),
        CONSTRAINT UQ_CB_SDT UNIQUE (SoDienThoai);

ALTER TABLE dbo.TAI_KHOAN
    ADD CONSTRAINT UQ_TK_TENDANGNHAP UNIQUE (TenDangNhap),
        CONSTRAINT UQ_TK_EMAIL UNIQUE (Email),
        CONSTRAINT UQ_TK_CANBO UNIQUE (Ma_CanBo);

ALTER TABLE dbo.TRANG_THAI_THANH_TOAN
    ADD CONSTRAINT UQ_TTTT_TEN UNIQUE (TenTrangThai);

ALTER TABLE dbo.LOAI_VI_PHAM
    ADD CONSTRAINT UQ_LVP_PT_MND UNIQUE (Ma_LoaiPhuongTien, Ma_MucNongDoCon);

ALTER TABLE dbo.QUYET_DINH_XU_PHAT
    ADD CONSTRAINT UQ_QD_VUVIEC UNIQUE (Ma_VuViec);

ALTER TABLE dbo.THANH_TOAN
    ADD CONSTRAINT UQ_TT_QUYETDINH UNIQUE (Ma_QuyetDinh);
GO

/* Chỉ cho phép một mức nồng độ không có ngưỡng trên (mức cao nhất). */
CREATE UNIQUE INDEX UX_MND_NguongTren
    ON dbo.MUC_NONG_DO_CON (NguongTren)
    WHERE NguongTren IS NOT NULL;

CREATE UNIQUE INDEX UX_MND_MotMucMo
    ON dbo.MUC_NONG_DO_CON (NguongTren)
    WHERE NguongTren IS NULL;
GO

/* Giấy phép lái xe (nếu có) không trùng. */
CREATE UNIQUE INDEX UX_NVP_SoGPLX
    ON dbo.NGUOI_VI_PHAM (SoGPLX)
    WHERE SoGPLX IS NOT NULL;
GO

/* ================= INDEX TÌM KIẾM ================= */
CREATE INDEX IX_NVP_HoTen ON dbo.NGUOI_VI_PHAM (HoTen);

CREATE INDEX IX_VV_ThoiGian ON dbo.VI_PHAM (ThoiGianViPham) INCLUDE (Ma_TrangThaiThanhToan, NongDoCon);
CREATE INDEX IX_VV_BienSo ON dbo.VI_PHAM (BienSoXe);
CREATE INDEX IX_VV_NguoiViPham ON dbo.VI_PHAM (Ma_NguoiViPham);
CREATE INDEX IX_VV_CanBo ON dbo.VI_PHAM (Ma_CanBo);
CREATE INDEX IX_VV_LoaiViPham ON dbo.VI_PHAM (Ma_LoaiViPham);
CREATE INDEX IX_VV_TrangThai ON dbo.VI_PHAM (Ma_TrangThaiThanhToan);

CREATE INDEX IX_QD_NgayRa ON dbo.QUYET_DINH_XU_PHAT (NgayRaQuyetDinh) INCLUDE (SoTienPhat, Ma_TrangThaiThanhToan);
CREATE INDEX IX_QD_TrangThai ON dbo.QUYET_DINH_XU_PHAT (Ma_TrangThaiThanhToan);

CREATE INDEX IX_TT_NgayNop ON dbo.THANH_TOAN (NgayNop) INCLUDE (SoTien);
CREATE INDEX IX_TT_CanBo ON dbo.THANH_TOAN (Ma_CanBo);

CREATE INDEX IX_TK_TrangThai ON dbo.TAI_KHOAN (TrangThai);
GO

PRINT N'Đã tạo khóa ngoại, ràng buộc và index.';
GO
